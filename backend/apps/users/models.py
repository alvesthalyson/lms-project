from django.contrib.auth.models import AbstractUser, BaseUserManager
from django.db import models


class Role(models.TextChoices):
    ADMIN = "ADMIN", "Admin"
    LIBRARIAN = "LIBRARIAN", "Librarian"
    MEMBER = "MEMBER", "Member"


class UserManager(BaseUserManager):
    use_in_migrations = True

    def _create_user(self, email, password, **extra_fields):
        if not email:
            raise ValueError("Email is required")
        user = self.model(email=self.normalize_email(email), **extra_fields)
        user.set_password(password)
        user.save(using=self._db)
        return user

    def create_user(self, email, password=None, **extra_fields):
        extra_fields.setdefault("is_staff", False)
        extra_fields.setdefault("is_superuser", False)
        return self._create_user(email, password, **extra_fields)

    def create_superuser(self, email, password=None, **extra_fields):
        extra_fields.setdefault("is_staff", True)
        extra_fields.setdefault("is_superuser", True)
        extra_fields.setdefault("role", Role.ADMIN)
        if not extra_fields["is_staff"] or not extra_fields["is_superuser"]:
            raise ValueError("Superuser needs is_staff=True and is_superuser=True")
        return self._create_user(email, password, **extra_fields)


class User(AbstractUser):
    """Custom user: log in with email, one role per user."""

    username = None
    email = models.EmailField(unique=True)
    role = models.CharField(
        max_length=10, choices=Role.choices, default=Role.MEMBER, db_index=True
    )
    member_number = models.CharField(
        max_length=20, unique=True, null=True, blank=True,
        help_text="Library card number, generated by the user service.",
    )
    phone = models.CharField(max_length=32, blank=True)
    address = models.TextField(blank=True)

    # Manual block set by staff. Automatic blocking (unpaid fines / overdue
    # loans) is computed in the service layer, not stored here.
    is_blocked = models.BooleanField(default=False)
    blocked_reason = models.CharField(max_length=255, blank=True)
    blocked_at = models.DateTimeField(null=True, blank=True)

    USERNAME_FIELD = "email"
    REQUIRED_FIELDS = ["first_name", "last_name"]

    objects = UserManager()

    class Meta:
        ordering = ["last_name", "first_name", "id"]
        indexes = [
            models.Index(fields=["role", "is_active"], name="user_role_active_idx"),
        ]

    @property
    def is_admin_role(self) -> bool:
        return self.role == Role.ADMIN

    @property
    def is_librarian_role(self) -> bool:
        return self.role == Role.LIBRARIAN

    @property
    def is_staff_role(self) -> bool:
        return self.role in (Role.ADMIN, Role.LIBRARIAN)

    def __str__(self):
        return self.get_full_name() or self.email
